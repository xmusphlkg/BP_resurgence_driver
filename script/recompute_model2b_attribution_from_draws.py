#!/usr/bin/env python3
"""Recompute Bayesian Model 2B attribution from existing posterior draws.

This is intentionally attribution-only: it requires CmdStan posterior draws and
Model 2B Stan JSON data that were already generated by the Bayesian pipeline.
It does not refit Stan and it does not fall back to deterministic outputs.
"""

from __future__ import annotations

import json
import os
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path
from typing import Any

import pandas as pd

from _bootstrap import add_project_src_to_path

add_project_src_to_path()

from pertussis_global_dynamics.bayes.model2b_attribution import (  # noqa: E402
    MODEL2B_OUTPUT_VERSION,
    MODEL2B_OUTCOMES,
    MODEL2B_PRIMARY_MECHANISMS,
    _metadata_bool,
    model2b_transmission_context_audit,
    model2b_observation_audit,
    model2b_posterior_predictive,
    model2b_shapley_draws,
    summarize_model2b_layered_attribution_summary,
    summarize_model2b_pooled_attribution,
    summarize_model2b_factor_weights,
)
from pertussis_global_dynamics.paths import FIGURE_DATA, OUTPUTS, ROOT  # noqa: E402


MODEL2B_DEFAULT_PILOT_ISO3 = ("AUS", "BRA", "CHN", "GBR", "JPN", "NZL", "SWE", "THA", "USA")


def _env_int(name: str, default: int, minimum: int = 1) -> int:
    raw = os.environ.get(name)
    if raw:
        try:
            return max(minimum, int(raw))
        except ValueError:
            return default
    return default


def _env_bool(name: str, default: bool = False) -> bool:
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in {"1", "true", "yes", "y", "on"}


def _manuscript_min_draws() -> int:
    return _env_int("MODEL2B_MIN_MANUSCRIPT_DRAWS", 2000)


def _complete_draw_input(draws: pd.DataFrame) -> tuple[bool, str]:
    if draws.empty or not {"iso3", "draw"}.issubset(draws.columns):
        return False, "missing_posterior_draws"
    expected_iso = set(MODEL2B_DEFAULT_PILOT_ISO3)
    observed_iso = set(draws["iso3"].dropna().astype(str))
    missing = sorted(expected_iso.difference(observed_iso))
    if missing:
        return False, "missing_countries_" + ",".join(missing)
    draw_counts = draws.loc[draws["iso3"].isin(expected_iso)].groupby("iso3")["draw"].nunique()
    min_draws = _manuscript_min_draws()
    too_few = sorted(draw_counts.loc[draw_counts.lt(min_draws)].index.astype(str).tolist())
    if too_few:
        return False, f"posterior_draws_below_{min_draws}_" + ",".join(too_few)
    return True, "complete_nine_country_manuscript_output"


def _first_existing(paths: list[Path], message: str) -> Path:
    for path in paths:
        if path.exists():
            return path
    checked = ", ".join(str(path.relative_to(ROOT)) for path in paths)
    raise SystemExit(f"{message}. Checked: {checked}")


def _mode_candidates(filename: str, contact_mode: str) -> list[Path]:
    path = OUTPUTS / filename
    stem = path.stem
    suffix = path.suffix
    suffixed = OUTPUTS / f"{stem}_{contact_mode}{suffix}"
    if contact_mode == "rank_one":
        return [suffixed]
    return [suffixed]


def _stan_data_path(iso3: str, contact_mode: str) -> Path:
    if contact_mode == "rank_one":
        candidates = [OUTPUTS / f"model2b_stan_data_{iso3}_rank_one.json"]
    else:
        candidates = [OUTPUTS / f"model2b_stan_data_{iso3}_{contact_mode}.json"]
    return _first_existing(candidates, f"Missing Model 2B Stan data JSON for {iso3}")


def _metadata_record(row: pd.Series) -> dict[str, Any]:
    record = {key: (None if pd.isna(value) else value) for key, value in row.to_dict().items()}
    for key in [
        "direct_testing_support",
        "direct_testing_denominator_evidence",
        "case_definition_reporting_practice_evidence",
        "severe_outcome_evidence",
        "serology_evidence",
        "pathogen_pressure_evidence",
        "model2b_contact_matrix_fallback",
        "adolescent_booster",
        "maternal_program_context",
    ]:
        if key in record:
            record[key] = _metadata_bool(record[key])
    return record


def _contact_mode_suffix() -> str:
    raw = os.environ.get("MODEL2B_CONTACT_MODE", "full").strip().lower().replace("-", "_")
    return "full" if raw == "full" else "rank_one"


def _write_contact_sensitivity_summary() -> None:
    columns = [
        "iso3",
        "country",
        "factor_id",
        "factor_label",
        "rank_one_share_percent",
        "full_contact_share_percent",
        "share_difference_full_minus_rank_one",
        "rank_one_rank",
        "full_contact_rank",
        "rank_change",
        "mechanism_rank_stable",
        "share_stability_band",
        "sensitivity_status",
        "model2b_output_version",
    ]
    rank_path = OUTPUTS / "model2b_bayes_factor_weight_summary_rank_one.csv"
    full_path = OUTPUTS / "model2b_bayes_factor_weight_summary_full.csv"
    output_path = OUTPUTS / "model2b_full_contact_sensitivity_summary.csv"
    missing = [path.name for path in (rank_path, full_path) if not path.exists()]
    if missing:
        pd.DataFrame(
            [
                {
                    "iso3": "ALL",
                    "country": "All countries",
                    "factor_id": "all_primary_mechanisms",
                    "factor_label": "All primary mechanisms",
                    "sensitivity_status": "missing_" + ";".join(missing),
                    "model2b_output_version": MODEL2B_OUTPUT_VERSION,
                }
            ],
            columns=columns,
        ).to_csv(output_path, index=False)
        return
    outcome = MODEL2B_OUTCOMES["true_infections"]
    rank_status = _factor_summary_status(rank_path, outcome)
    full_status = _factor_summary_status(full_path, outcome)
    invalid = [status for status in (rank_status, full_status) if status != "ok"]
    if invalid:
        pd.DataFrame(
            [
                {
                    "iso3": "ALL",
                    "country": "All countries",
                    "factor_id": "all_primary_mechanisms",
                    "factor_label": "All primary mechanisms",
                    "sensitivity_status": "invalid_" + ";".join(invalid),
                    "model2b_output_version": MODEL2B_OUTPUT_VERSION,
                }
            ],
            columns=columns,
        ).to_csv(output_path, index=False)
        return
    rank = pd.read_csv(rank_path)
    full = pd.read_csv(full_path)
    rank = rank.loc[rank["outcome_target"].eq(outcome)].copy()
    full = full.loc[full["outcome_target"].eq(outcome)].copy()
    for frame in (rank, full):
        frame["share_percent_median"] = pd.to_numeric(frame["share_percent_median"], errors="coerce")
        frame["positive_rank_basis"] = frame["share_percent_median"].where(frame["share_percent_median"].gt(0), float("-inf"))
        frame["mechanism_rank"] = (
            frame.sort_values(
                ["iso3", "positive_rank_basis", "share_percent_median", "factor_id"],
                ascending=[True, False, False, True],
                kind="stable",
            )
            .groupby("iso3")
            .cumcount()
            + 1
        )
    merged = rank.merge(full, on=["iso3", "factor_id"], how="outer", suffixes=("_rank_one", "_full"))
    rows = []
    for row in merged.itertuples(index=False):
        rank_share = getattr(row, "share_percent_median_rank_one", float("nan"))
        full_share = getattr(row, "share_percent_median_full", float("nan"))
        share_diff = full_share - rank_share if pd.notna(rank_share) and pd.notna(full_share) else float("nan")
        rank_one_rank = getattr(row, "mechanism_rank_rank_one", float("nan"))
        full_contact_rank = getattr(row, "mechanism_rank_full", float("nan"))
        rank_change = full_contact_rank - rank_one_rank if pd.notna(rank_one_rank) and pd.notna(full_contact_rank) else float("nan")
        rows.append(
            {
                "iso3": getattr(row, "iso3"),
                "country": getattr(row, "country_rank_one", None) or getattr(row, "country_full", None),
                "factor_id": getattr(row, "factor_id"),
                "factor_label": getattr(row, "factor_label_rank_one", None) or getattr(row, "factor_label_full", None),
                "rank_one_share_percent": rank_share,
                "full_contact_share_percent": full_share,
                "share_difference_full_minus_rank_one": share_diff,
                "rank_one_rank": rank_one_rank,
                "full_contact_rank": full_contact_rank,
                "rank_change": rank_change,
                "mechanism_rank_stable": bool(rank_change == 0) if pd.notna(rank_change) else False,
                "share_stability_band": "stable_within_5pp" if pd.notna(share_diff) and abs(share_diff) <= 5.0 else "shift_gt_5pp",
                "sensitivity_status": "compared_rank_one_vs_full",
                "model2b_output_version": MODEL2B_OUTPUT_VERSION,
            }
        )
    pd.DataFrame(rows, columns=columns).to_csv(output_path, index=False)


def _factor_summary_status(path: Path, outcome: str) -> str:
    if not path.exists():
        return "missing_" + path.name
    frame = pd.read_csv(path)
    required = {"iso3", "factor_id", "outcome_target", "n_posterior_draws", "model2b_output_version"}
    missing_columns = sorted(required.difference(frame.columns))
    if missing_columns:
        return f"{path.name}_missing_columns_" + ",".join(missing_columns)
    versions = set(frame["model2b_output_version"].dropna().astype(str))
    if versions != {MODEL2B_OUTPUT_VERSION}:
        return f"{path.name}_output_version_mismatch"
    true = frame.loc[frame["outcome_target"].eq(outcome)].copy()
    expected_iso = set(MODEL2B_DEFAULT_PILOT_ISO3)
    expected_factors = set(MODEL2B_PRIMARY_MECHANISMS)
    observed_iso = set(true["iso3"].dropna().astype(str))
    missing_iso = sorted(expected_iso.difference(observed_iso))
    if missing_iso:
        return f"{path.name}_missing_countries_" + ",".join(missing_iso)
    expected_pairs = {(iso3, factor_id) for iso3 in expected_iso for factor_id in expected_factors}
    observed_pairs = {
        (str(row.iso3), str(row.factor_id))
        for row in true.loc[true["iso3"].isin(expected_iso)].itertuples(index=False)
    }
    missing_pairs = sorted(expected_pairs.difference(observed_pairs))
    if missing_pairs:
        preview = ",".join(f"{iso3}:{factor_id}" for iso3, factor_id in missing_pairs[:5])
        return f"{path.name}_missing_factor_rows_" + preview
    true["n_posterior_draws"] = pd.to_numeric(true["n_posterior_draws"], errors="coerce")
    min_draws = _manuscript_min_draws()
    too_few = sorted(
        true.loc[true["n_posterior_draws"].lt(min_draws), "iso3"].dropna().astype(str).unique().tolist()
    )
    if too_few:
        return f"{path.name}_posterior_draws_below_{min_draws}_" + ",".join(too_few)
    return "ok"


def _run_country(payload: tuple[str, Path, pd.DataFrame, dict[str, Any]]) -> dict[str, pd.DataFrame]:
    iso3, data_path, draws, metadata = payload
    with data_path.open(encoding="utf-8") as handle:
        data = json.load(handle)

    country_draws = draws.loc[draws["iso3"].eq(iso3)].drop(columns=["iso3", "country"])
    if country_draws.empty:
        raise SystemExit(f"No posterior draws found for {iso3} in outputs/model2b_bayes_posterior_draws.csv")

    shapley = model2b_shapley_draws(data, country_draws)
    if not shapley.empty:
        shapley.insert(0, "country", metadata["country"])
        shapley.insert(0, "iso3", iso3)
    factor_summary = summarize_model2b_factor_weights(shapley, iso3, metadata["country"])
    layered_attribution_summary = summarize_model2b_layered_attribution_summary(shapley, iso3, metadata["country"])
    observation_audit = model2b_observation_audit(data, metadata, country_draws)
    transmission_context_audit = model2b_transmission_context_audit(data, metadata, country_draws)
    posterior_predictive = model2b_posterior_predictive(data, metadata, country_draws)
    return {
        "shapley_draws": shapley,
        "factor_summary": factor_summary,
        "layered_attribution_summary": layered_attribution_summary,
        "observation_audit": observation_audit,
        "transmission_context_audit": transmission_context_audit,
        "posterior_predictive": posterior_predictive,
    }


def _write_versioned_input_outputs(draws: pd.DataFrame, contact_mode: str, suffix_mode: str, complete_output: bool) -> None:
    versioned_draws = draws.copy()
    versioned_draws["model2b_output_version"] = MODEL2B_OUTPUT_VERSION
    draw_stem = "model2b_bayes_posterior_draws"
    versioned_draws.to_csv(OUTPUTS / f"{draw_stem}_{suffix_mode}.csv", index=False)
    if complete_output and contact_mode == "full":
        versioned_draws.to_csv(OUTPUTS / f"{draw_stem}.csv", index=False)

    fit_path = _first_existing(
        _mode_candidates("model2b_bayes_fit_summary.csv", contact_mode),
        "Missing Model 2B fit summary",
    )
    fit = pd.read_csv(fit_path)
    fit["model2b_output_version"] = MODEL2B_OUTPUT_VERSION
    fit_stem = "model2b_bayes_fit_summary"
    fit.to_csv(OUTPUTS / f"{fit_stem}_{suffix_mode}.csv", index=False)
    if complete_output and contact_mode == "full":
        fit.to_csv(OUTPUTS / f"{fit_stem}.csv", index=False)


def main() -> None:
    contact_mode = _contact_mode_suffix()
    draws_path = _first_existing(
        _mode_candidates("model2b_bayes_posterior_draws.csv", contact_mode),
        "Missing Model 2B posterior draws",
    )
    metadata_path = _first_existing(
        _mode_candidates("model2b_stan_data_metadata.csv", contact_mode),
        "Missing Model 2B Stan metadata",
    )
    draws = pd.read_csv(draws_path)
    metadata = pd.read_csv(metadata_path)
    missing = {"iso3", "country"}.difference(draws.columns)
    if missing:
        raise SystemExit(f"{draws_path.relative_to(ROOT)} is missing required columns: {', '.join(sorted(missing))}")
    missing = {"iso3", "country"}.difference(metadata.columns)
    if missing:
        raise SystemExit(f"{metadata_path.relative_to(ROOT)} is missing required columns: {', '.join(sorted(missing))}")

    countries = [iso3 for iso3 in metadata["iso3"].dropna().astype(str).tolist() if iso3 in set(draws["iso3"])]
    workers = min(len(countries), _env_int("MODEL2B_ATTRIBUTION_COUNTRY_WORKERS", _env_int("MODEL2B_COUNTRY_WORKERS", 1)))
    payloads = [
        (
            iso3,
            _stan_data_path(iso3, contact_mode),
            draws,
            _metadata_record(metadata.loc[metadata["iso3"].astype(str).eq(iso3)].iloc[0]),
        )
        for iso3 in countries
    ]
    if workers > 1:
        tables: list[dict[str, pd.DataFrame] | None] = [None for _ in payloads]
        with ProcessPoolExecutor(max_workers=workers) as executor:
            futures = {executor.submit(_run_country, payload): index for index, payload in enumerate(payloads)}
            for completed, future in enumerate(as_completed(futures), start=1):
                index = futures[future]
                tables[index] = future.result()
                print(f"Recomputed Model 2B attribution for {payloads[index][0]} ({completed}/{len(payloads)}).", flush=True)
        country_tables = [table for table in tables if table is not None]
    else:
        country_tables = [_run_country(payload) for payload in payloads]

    combined = {
        name: pd.concat([item[name] for item in country_tables], ignore_index=True, sort=False)
        for name in [
            "shapley_draws",
            "factor_summary",
            "layered_attribution_summary",
            "observation_audit",
            "transmission_context_audit",
            "posterior_predictive",
        ]
    }
    OUTPUTS.mkdir(parents=True, exist_ok=True)
    FIGURE_DATA.mkdir(parents=True, exist_ok=True)
    output_paths = {
        "shapley_draws": "model2b_bayes_shapley_draws.csv",
        "factor_summary": "model2b_bayes_factor_weight_summary.csv",
        "layered_attribution_summary": "model2b_bayes_layered_attribution_summary.csv",
        "observation_audit": "model2b_bayes_observation_process_audit.csv",
        "transmission_context_audit": "model2b_bayes_transmission_context_audit.csv",
        "posterior_predictive": "model2b_bayes_posterior_predictive.csv",
    }
    complete_output, completeness_status = _complete_draw_input(draws)
    if not complete_output:
        print(
            "Model 2B draw input is not a complete manuscript output: "
            f"{completeness_status}. Writing partial attribution files only.",
            flush=True,
        )
    suffix_mode = contact_mode if complete_output else f"partial_{contact_mode}"
    _write_versioned_input_outputs(draws, contact_mode, suffix_mode, complete_output)
    for name, filename in output_paths.items():
        stem = filename.removesuffix(".csv")
        combined[name].to_csv(OUTPUTS / f"{stem}_{suffix_mode}.csv", index=False)
        if complete_output and contact_mode == "full":
            combined[name].to_csv(OUTPUTS / filename, index=False)
    pooled = summarize_model2b_pooled_attribution(combined["shapley_draws"])
    pooled.to_csv(OUTPUTS / f"model2b_bayes_pooled_9country_attribution_{suffix_mode}.csv", index=False)
    if complete_output and contact_mode == "full":
        pooled.to_csv(OUTPUTS / "model2b_bayes_pooled_9country_attribution.csv", index=False)
    _write_contact_sensitivity_summary()
    figure_data = combined["factor_summary"].loc[
        combined["factor_summary"]["outcome_target"].eq(MODEL2B_OUTCOMES["true_infections"])
    ].copy()
    figure_data.to_csv(FIGURE_DATA / f"figure_4_bayesian_transmission_attribution_{suffix_mode}.csv", index=False)
    if complete_output and contact_mode == "full":
        figure_data.to_csv(FIGURE_DATA / "figure_4_bayesian_transmission_attribution.csv", index=False)
    if not complete_output and _env_bool("MODEL2B_REQUIRE_MANUSCRIPT_OUTPUTS", False):
        raise SystemExit(
            "Refusing to update Model 2B manuscript-default attribution from incomplete draws: "
            f"{completeness_status}."
        )
    print(f"Wrote attribution-only Model 2B outputs for {len(country_tables)} countries.")


if __name__ == "__main__":
    main()
