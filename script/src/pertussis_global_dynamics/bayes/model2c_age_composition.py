from __future__ import annotations

from collections import defaultdict
from pathlib import Path
from typing import Any


DATA_BLOCK_OLD = """  int<lower=0> N_age_obs;
  array[N_age_obs] int<lower=1, upper=N_years> age_obs_year_idx;
  array[N_age_obs] int<lower=1, upper=N_age> age_obs_age_idx;
  array[N_age_obs] int<lower=0> y_age;
  vector<lower=0.0, upper=1.0>[N_age_obs] age_obs_weight;
"""

DATA_BLOCK_NEW = """  // Annual age composition, conditional on the observed annual age total.
  int<lower=0> N_age_comp_years;
  int<lower=0> N_age_comp_cells;
  array[N_age_comp_years] int<lower=1, upper=N_years> age_comp_year_idx;
  array[N_age_comp_years] int<lower=1, upper=N_age_comp_cells + 1> age_comp_start;
  array[N_age_comp_years] int<lower=1, upper=N_age> age_comp_len;
  array[N_age_comp_cells] int<lower=1, upper=N_age> age_comp_age_idx;
  array[N_age_comp_cells] int<lower=0> y_age_comp;
  vector<lower=0.0, upper=1.0>[N_age_comp_years] age_comp_weight;
"""

LIKELIHOOD_OLD = """  for (i in 1:N_age_obs) {
    target += age_obs_weight[i]
      * neg_binomial_2_lpmf(y_age[i] | mu_year_age[age_obs_year_idx[i], age_obs_age_idx[i]] + 1e-6, nb_phi_age);
  }
"""

LIKELIHOOD_NEW = """  // The monthly all-age term identifies annual magnitude. This term uses only
  // within-year age composition, avoiding a second likelihood for the same total.
  for (g in 1:N_age_comp_years) {
    int K = age_comp_len[g];
    int first = age_comp_start[g];
    array[K] int counts;
    vector[K] log_mu;
    vector[K] alpha;
    for (k in 1:K) {
      int cell = first + k - 1;
      counts[k] = y_age_comp[cell];
      log_mu[k] = log(mu_year_age[age_comp_year_idx[g], age_comp_age_idx[cell]] + 1e-9);
    }
    alpha = softmax(log_mu) * nb_phi_age;
    target += age_comp_weight[g] * dirichlet_multinomial_lpmf(counts | alpha);
  }
"""


def augment_age_composition_data(data: dict[str, Any]) -> dict[str, Any]:
    """Add ragged annual age-composition arrays to existing Model 2C Stan data."""
    required = ("N_age_obs", "age_obs_year_idx", "age_obs_age_idx", "y_age", "age_obs_weight")
    missing = [name for name in required if name not in data]
    if missing:
        raise ValueError(f"Missing age-observation fields: {', '.join(missing)}")

    n_obs = int(data["N_age_obs"])
    columns = [data[name] for name in required[1:]]
    if any(len(values) != n_obs for values in columns):
        raise ValueError("Age-observation arrays do not match N_age_obs.")

    grouped: dict[int, list[tuple[int, int, float]]] = defaultdict(list)
    for year_idx, age_idx, count, weight in zip(*columns):
        grouped[int(year_idx)].append((int(age_idx), int(count), float(weight)))

    year_indices: list[int] = []
    starts: list[int] = []
    lengths: list[int] = []
    age_indices: list[int] = []
    counts: list[int] = []
    group_weights: list[float] = []
    for year_idx in sorted(grouped):
        cells = sorted(grouped[year_idx])
        observed_ages = [cell[0] for cell in cells]
        if len(set(observed_ages)) != len(observed_ages):
            raise ValueError(f"Duplicate age cells for year index {year_idx}.")
        year_indices.append(year_idx)
        starts.append(len(age_indices) + 1)  # Stan uses one-based indexing.
        lengths.append(len(cells))
        age_indices.extend(observed_ages)
        counts.extend(cell[1] for cell in cells)
        # One annual composition contributes one unit. Retaining the original
        # cell weights here would confound the structural sensitivity with a
        # second, outcome-dependent learning-rate choice.
        group_weights.append(1.0)

    augmented = dict(data)
    augmented.update(
        {
            "N_age_comp_years": len(year_indices),
            "N_age_comp_cells": len(age_indices),
            "age_comp_year_idx": year_indices,
            "age_comp_start": starts,
            "age_comp_len": lengths,
            "age_comp_age_idx": age_indices,
            "y_age_comp": counts,
            "age_comp_weight": group_weights,
        }
    )
    return augmented


def derive_age_composition_stan(base_source: str) -> str:
    """Derive the isolated conditional-composition Stan program exactly once."""
    if base_source.count(DATA_BLOCK_OLD) != 1:
        raise ValueError("Base Stan age-observation data block changed; refusing an ambiguous rewrite.")
    if base_source.count(LIKELIHOOD_OLD) != 1:
        raise ValueError("Base Stan age likelihood changed; refusing an ambiguous rewrite.")
    return (
        base_source.replace(DATA_BLOCK_OLD, DATA_BLOCK_NEW)
        .replace(LIKELIHOOD_OLD, LIKELIHOOD_NEW)
        .replace(
            "data {",
            "// GENERATED structural sensitivity: monthly all-age NB + conditional annual age DM.\n"
            "// Source is generated by run_model2c_age_composition.py; do not edit by hand.\n"
            "data {",
            1,
        )
    )


def write_age_composition_stan(base_path: Path, output_path: Path) -> Path:
    source = derive_age_composition_stan(base_path.read_text(encoding="utf-8"))
    if not output_path.exists() or output_path.read_text(encoding="utf-8") != source:
        output_path.write_text(source, encoding="utf-8")
    return output_path
